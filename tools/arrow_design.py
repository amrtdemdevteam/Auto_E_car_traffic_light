"""T3 green arrow design (style A, 31 frames) — source of truth for the ESP32 bitmaps.

Each frame is a direction mask: bit0 L (ซ้าย), bit1 UL (เฉียงซ้าย), bit2 U (ตรง),
bit3 UR (เฉียงขวา), bit4 R (ขวา). Frame number = mask value (1..31).

Run `python3 tools/arrow_design.py` to regenerate
esp32_display_t3/src/arrow_bitmaps.h and the preview sheet.
"""
from __future__ import annotations

import math
import os
import sys

W, H = 64, 32
CX = 31.5
R2 = math.sqrt(2)
BITS = {"L": 1, "UL": 2, "U": 4, "UR": 8, "R": 16}
SW, HL, HW = 2.3, 9.0, 6.5  # stroke half-width, head length, head half-width


def _segd(px, py, a, b):
    (x1, y1), (x2, y2) = a, b
    vx, vy = x2 - x1, y2 - y1
    L = vx * vx + vy * vy
    t = 0 if L == 0 else max(0, min(1, ((px - x1) * vx + (py - y1) * vy) / L))
    return math.hypot(px - (x1 + t * vx), py - (y1 + t * vy))


def _intri(px, py, a, b, c):
    def s(p, q, r):
        return (p[0] - r[0]) * (q[1] - r[1]) - (q[0] - r[0]) * (p[1] - r[1])
    d1, d2, d3 = s((px, py), a, b), s((px, py), b, c), s((px, py), c, a)
    return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))


def _bez(p0, p1, p2, n=20):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1])
            for t in [i / n for i in range(n + 1)]]


def _head(tip, ux, uy, hl=HL, hw=HW):
    n = math.hypot(ux, uy)
    ux, uy = ux / n, uy / n
    bx, by = tip[0] - ux * hl, tip[1] - uy * hl
    nx, ny = -uy, ux
    return (bx, by), (tip, (bx + nx * hw, by + ny * hw), (bx - nx * hw, by - ny * hw))


def _render(paths, heads, sw=SW):
    on = set()
    for y in range(H):
        for x in range(W):
            px, py = x + 0.5, y + 0.5
            if any(_intri(px, py, *t) for t in heads):
                on.add((x, y))
                continue
            for pts in paths:
                if any(_segd(px, py, pts[i], pts[i + 1]) <= sw for i in range(len(pts) - 1)):
                    on.add((x, y))
                    break
    return on


def make(dirs):
    """Pixels (x, y) lit for a set of direction names, e.g. {'U', 'UR'}."""
    has_u = "U" in dirs
    hL, hR = "L" in dirs, "R" in dirs
    side = (1 if hL else 0) - (1 if hR else 0)
    sx = CX + (5 if has_u else 6) * side
    P, T = [], []
    if has_u:
        b, t = _head((sx, 0.6), 0, -1)
        P.append([(sx, 31.5), b])
        T.append(t)
    tops = []
    for s, d in ((-1, "L"), (1, "R")):
        if d not in dirs:
            continue
        if len([x for x in ("L", "R") if x in dirs]) == 1 and not has_u and not any(
                x in dirs for x in ("UL", "UR")):
            y_arm, y_from, X = 9.5, 16.0, 15.5
        else:
            y_arm, y_from = 17.5, 25.5
            X = 20.0 if (hL and hR) else 15.5
        if (s == -1 and "UL" in dirs) or (s == 1 and "UR" in dirs):
            y_arm, y_from = 20.0, 27.0
        tops.append(y_from)
        b, t = _head((CX + s * X, y_arm), s, 0)
        r = min(7.0, y_from - y_arm)
        P.append(_bez((sx, y_from), (sx, y_arm), (sx + s * r, y_arm)) + [b])
        T.append(t)
    rr = 8.0
    for s, d in ((-1, "UL"), (1, "UR")):
        if d not in dirs:
            continue
        same = (s == -1 and hL) or (s == 1 and hR)
        Cy, D = (12.0, 14.0) if same else (19.0, 19.0)
        u = (s / R2, -1 / R2)
        P0 = (sx, Cy + rr)
        P2 = (sx + u[0] * rr, Cy + u[1] * rr)
        tip = (sx + u[0] * D, Cy + u[1] * D)
        b, t = _head(tip, u[0], u[1])
        P.append(_bez(P0, (sx, Cy), P2) + [b])
        T.append(t)
        tops.append(Cy + rr)
    if not has_u:
        P.append([(sx, 31.5), (sx, min(tops))])
    on = _render(P, T)
    xs = [x for x, _ in on]
    ys = [y for _, y in on]
    dx = (W - 1 - max(xs) - min(xs)) // 2
    dy = (H - 1 - max(ys) - min(ys)) // 2
    return {(x + dx, y + dy) for x, y in on if 0 <= x + dx < W and 0 <= y + dy < H}


def dirs_of(mask):
    return {d for d, b in BITS.items() if mask & b}


def bitmaps():
    """{mask: [32 row ints, bit x = pixel x]} for mask 1..31."""
    out = {}
    for mask in range(1, 32):
        on = make(dirs_of(mask))
        rows = [0] * H
        for x, y in on:
            rows[y] |= 1 << x
        out[mask] = rows
    return out


def write_header(path):
    maps = bitmaps()
    lines = [
        "// GENERATED by tools/arrow_design.py - do not edit by hand.",
        "// ARROW frame bitmaps (style A, 31 frames). Index = mask-1.",
        "// Mask bits: 1=L 2=UL 4=U 8=UR 16=R. Row y, bit x = pixel (x,y).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint64_t ARROW_BITMAP[31][32] = {",
    ]
    for mask in range(1, 32):
        lines.append(f"  {{  // {mask}")
        for y in range(H):
            lines.append(f"    0x{maps[mask][y]:016X}ULL,")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


JS_BEGIN = "  // ARROW_BITMAP_BEGIN (generated by tools/arrow_design.py)"
JS_END = "  // ARROW_BITMAP_END"


def write_js(path):
    """Replace the bitmap block in web/static/led.js (rows as 16-hex-digit strings)."""
    maps = bitmaps()
    rows = ",".join("'" + "".join(f"{r:016X}" for r in maps[m]) + "'" for m in range(1, 32))
    block = f"{JS_BEGIN}\n  var ARROW_BITMAP = [{rows}];\n{JS_END}"
    with open(path, encoding="utf-8") as f:
        src = f.read()
    a, b = src.index(JS_BEGIN), src.index(JS_END) + len(JS_END)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(src[:a] + block + src[b:])


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    write_header(os.path.join(root, "esp32_display_t3", "src", "arrow_bitmaps.h"))
    write_js(os.path.join(root, "raspberry_pi", "trafficlight", "web", "static", "led.js"))
    print("wrote esp32_display_t3/src/arrow_bitmaps.h and web/static/led.js bitmaps")
